-- Preserve every changed library original. History is private to its owner,
-- even when the current item or the historical snapshot was team-shared.
BEGIN;
SET LOCAL lock_timeout='5s';
SET LOCAL statement_timeout='60s';
DO $$ BEGIN
 IF to_regclass('public.ps_library') IS NULL OR to_regclass('public.ps_blob') IS NULL
 OR to_regprocedure('public.ps_is_member(uuid)') IS NULL THEN
  RAISE EXCEPTION 'library recovery: required source schema missing' USING ERRCODE='55000';
 END IF;
 IF to_regclass('public.ps_library_history') IS NOT NULL OR to_regclass('public.ps_library_restore_requests') IS NOT NULL
 OR to_regprocedure('public.ps_library_capture_history_v1()') IS NOT NULL THEN
  RAISE EXCEPTION 'library recovery: objects already exist; verify instead of overwriting' USING ERRCODE='55000';
 END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.ps_library_history (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 workspace_id uuid NOT NULL REFERENCES public.ps_workspaces(id) ON DELETE CASCADE,
 lib_id text NOT NULL, owner_id uuid, snapshot jsonb NOT NULL,
 kind text NOT NULL CHECK(kind IN ('update','delete','conflict')),
 actor_id uuid, created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 dedupe_key text
);
CREATE UNIQUE INDEX IF NOT EXISTS ps_library_history_dedupe
 ON public.ps_library_history(workspace_id,owner_id,lib_id,dedupe_key) WHERE dedupe_key IS NOT NULL;
CREATE INDEX IF NOT EXISTS ps_library_history_owner_at
 ON public.ps_library_history(workspace_id,owner_id,created_at DESC,id DESC);
ALTER TABLE public.ps_library_history ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS ps_library_history_owner ON public.ps_library_history;
CREATE POLICY ps_library_history_owner ON public.ps_library_history FOR SELECT TO authenticated
 USING(owner_id=auth.uid() AND public.ps_is_member(workspace_id));
REVOKE ALL ON public.ps_library_history FROM PUBLIC,anon,authenticated;
GRANT SELECT ON public.ps_library_history TO authenticated;
REVOKE ALL ON SEQUENCE public.ps_library_history_id_seq FROM PUBLIC,anon,authenticated;

CREATE TABLE IF NOT EXISTS public.ps_library_restore_requests (
 request_id uuid PRIMARY KEY,workspace_id uuid NOT NULL REFERENCES public.ps_workspaces(id) ON DELETE CASCADE,
 owner_id uuid NOT NULL,history_id bigint NOT NULL REFERENCES public.ps_library_history(id) ON DELETE CASCADE,
 lib_id text NOT NULL,created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
ALTER TABLE public.ps_library_restore_requests ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.ps_library_restore_requests FROM PUBLIC,anon,authenticated;

CREATE OR REPLACE FUNCTION public.ps_library_capture_history_v1() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public AS $$
DECLARE old_content jsonb; new_content jsonb;
BEGIN
 IF TG_OP='UPDATE' THEN
  -- Autosave timestamps alone are not a new original. Compare content and all
  -- access/organization fields; the stored snapshot below remains the FULL OLD row.
  old_content:=to_jsonb(OLD)-'updated_at'-'saved_at';
  new_content:=to_jsonb(NEW)-'updated_at'-'saved_at';
  IF jsonb_typeof(OLD.item)='object' THEN old_content:=jsonb_set(old_content,'{item}',OLD.item-'savedAt'); END IF;
  IF jsonb_typeof(NEW.item)='object' THEN new_content:=jsonb_set(new_content,'{item}',NEW.item-'savedAt'); END IF;
  IF old_content IS NOT DISTINCT FROM new_content THEN RETURN NEW; END IF;
 END IF;
 INSERT INTO public.ps_library_history(workspace_id,lib_id,owner_id,snapshot,kind,actor_id)
 VALUES(OLD.workspace_id,OLD.lib_id,OLD.owner_id,to_jsonb(OLD),lower(TG_OP),auth.uid());
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION public.ps_library_capture_history_v1() FROM PUBLIC,anon,authenticated;
DROP TRIGGER IF EXISTS ps_library_recovery_capture ON public.ps_library;
CREATE TRIGGER ps_library_recovery_capture BEFORE UPDATE OR DELETE ON public.ps_library
 FOR EACH ROW EXECUTE FUNCTION public.ps_library_capture_history_v1();

CREATE OR REPLACE FUNCTION public.ps_library_history_list_v1(p_wid uuid,p_limit integer DEFAULT 30)
RETURNS TABLE(id bigint,lib_id text,name text,kind text,created_at timestamptz)
LANGUAGE sql STABLE SECURITY INVOKER SET search_path=pg_catalog,public AS $$
 SELECT h.id,h.lib_id,coalesce(h.snapshot->>'name',''),h.kind,h.created_at
 FROM public.ps_library_history h WHERE h.workspace_id=p_wid AND jsonb_typeof(h.snapshot->'item')='object'
 ORDER BY h.created_at DESC,h.id DESC LIMIT greatest(1,least(coalesce(p_limit,30),100))
$$;
CREATE OR REPLACE FUNCTION public.ps_library_history_get_v1(p_wid uuid,p_id bigint)
RETURNS TABLE(id bigint,lib_id text,snapshot jsonb,kind text,created_at timestamptz)
LANGUAGE sql STABLE SECURITY INVOKER SET search_path=pg_catalog,public AS $$
 SELECT h.id,h.lib_id,h.snapshot,h.kind,h.created_at FROM public.ps_library_history h
 WHERE h.workspace_id=p_wid AND h.id=p_id
$$;

CREATE OR REPLACE FUNCTION public.ps_library_archive_conflict_v1(p_wid uuid,p_lib_id text,p_snapshot jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public AS $$
DECLARE me uuid:=auth.uid(); source public.ps_library%ROWTYPE; snap jsonb; hid bigint; key text;
BEGIN
 IF me IS NULL OR NOT public.ps_is_member(p_wid) THEN RAISE EXCEPTION 'library recovery: membership required' USING ERRCODE='42501'; END IF;
 SELECT * INTO source FROM public.ps_library WHERE workspace_id=p_wid AND lib_id=p_lib_id FOR SHARE;
 IF NOT FOUND OR source.owner_id IS DISTINCT FROM me THEN RAISE EXCEPTION 'library recovery: owner required' USING ERRCODE='42501'; END IF;
 IF jsonb_typeof(p_snapshot) IS DISTINCT FROM 'object'
 OR jsonb_typeof(p_snapshot->'item') IS DISTINCT FROM 'object'
 OR p_snapshot->>'lib_id' IS DISTINCT FROM p_lib_id
 OR p_snapshot->>'owner_id' IS DISTINCT FROM me::text
 OR p_snapshot->>'workspace_id' IS DISTINCT FROM p_wid::text THEN
  RAISE EXCEPTION 'library recovery: invalid snapshot' USING ERRCODE='22023';
 END IF;
 -- This uses the dedicated non-bypass reader, not this function's definer role.
 -- Missing privacy migration fails closed before the local source may be replaced.
 PERFORM public.ps_blob_assert_refs_v1(p_wid,p_snapshot->'item',NULL);
 snap:=p_snapshot||jsonb_build_object('private',true,'owner_id',me,'workspace_id',p_wid,'lib_id',p_lib_id);
 key:='conflict:'||md5(snap::text);
 INSERT INTO public.ps_library_history(workspace_id,lib_id,owner_id,snapshot,kind,actor_id,dedupe_key)
 VALUES(p_wid,p_lib_id,me,snap,'conflict',me,key)
 ON CONFLICT(workspace_id,owner_id,lib_id,dedupe_key) WHERE dedupe_key IS NOT NULL DO NOTHING RETURNING id INTO hid;
 IF hid IS NULL THEN
  SELECT id INTO hid FROM public.ps_library_history WHERE workspace_id=p_wid AND owner_id=me AND lib_id=p_lib_id AND dedupe_key=key AND snapshot=snap;
  IF hid IS NULL THEN RAISE EXCEPTION 'library recovery: archive identity conflict' USING ERRCODE='40001'; END IF;
 END IF;
 RETURN jsonb_build_object('id',hid,'preserved',true);
END $$;

CREATE OR REPLACE FUNCTION public.ps_library_restore_copy_v1(p_wid uuid,p_id bigint,p_request_id uuid)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public AS $$
DECLARE me uuid:=auth.uid(); h public.ps_library_history%ROWTYPE; request public.ps_library_restore_requests%ROWTYPE;
 new_id text; target public.ps_library%ROWTYPE; item jsonb; stamp bigint; title text; inserted uuid;
BEGIN
 IF me IS NULL OR NOT public.ps_is_member(p_wid) THEN RAISE EXCEPTION 'library recovery: membership required' USING ERRCODE='42501'; END IF;
 SELECT * INTO h FROM public.ps_library_history WHERE workspace_id=p_wid AND id=p_id AND owner_id=me FOR SHARE;
 IF NOT FOUND OR jsonb_typeof(h.snapshot->'item') IS DISTINCT FROM 'object' THEN RAISE EXCEPTION 'library recovery: original unavailable' USING ERRCODE='42501'; END IF;
 IF p_request_id IS NULL THEN RAISE EXCEPTION 'library recovery: request identity required' USING ERRCODE='22023'; END IF;
 item:=h.snapshot->'item';
 -- All historical references must still be available; a partial photo restore is not success.
 PERFORM public.ps_blob_assert_refs_v1(p_wid,item,NULL);
 IF EXISTS(SELECT 1 FROM public.ps_blob_refs_json_v1(item) AS ref(h)
   WHERE NOT EXISTS(SELECT 1 FROM public.ps_blob b WHERE b.workspace_id=p_wid AND b.h=ref.h)) THEN
  RAISE EXCEPTION 'library recovery: original photo missing' USING ERRCODE='55000';
 END IF;
 new_id:='R'||replace(p_request_id::text,'-','');
 INSERT INTO public.ps_library_restore_requests(request_id,workspace_id,owner_id,history_id,lib_id)
 VALUES(p_request_id,p_wid,me,p_id,new_id) ON CONFLICT(request_id) DO NOTHING RETURNING request_id INTO inserted;
 IF inserted IS NULL THEN
  SELECT * INTO request FROM public.ps_library_restore_requests WHERE request_id=p_request_id;
  IF request.owner_id IS DISTINCT FROM me OR request.workspace_id IS DISTINCT FROM p_wid OR request.history_id IS DISTINCT FROM p_id THEN
   RAISE EXCEPTION 'library recovery: request identity conflict' USING ERRCODE='40001';
  END IF;
  SELECT * INTO target FROM public.ps_library WHERE workspace_id=p_wid AND lib_id=request.lib_id FOR SHARE;
  IF NOT FOUND OR target.owner_id IS DISTINCT FROM me OR target.private IS DISTINCT FROM true OR target.deleted_at IS NOT NULL OR jsonb_typeof(target.item) IS DISTINCT FROM 'object' THEN
   RAISE EXCEPTION 'library recovery: restored copy unavailable' USING ERRCODE='55000';
  END IF;
  RETURN jsonb_build_object('lib_id',request.lib_id,'restored',true,'repeated',true);
 END IF;
 stamp:=floor(extract(epoch FROM clock_timestamp())*1000)::bigint;
 title:=coalesce(nullif(h.snapshot->>'name',''),'자료')||' · 복구';
 item:=(item-'_teamSharedAt'-'_teamSource'-'_teamOwner'-'_teamSharePending'-'matchRef')
  ||jsonb_build_object('libId',new_id,'name',title,'folder','','pin',false,'createdBy',me,'savedAt',stamp,'editedAt',stamp);
 INSERT INTO public.ps_library(workspace_id,lib_id,type,name,folder,tags,pin,item,saved_at,deleted_at,owner_id,private)
 VALUES(p_wid,new_id,coalesce(h.snapshot->>'type','board'),title,'',coalesce(h.snapshot->'tags','[]'::jsonb),false,item,stamp,NULL,me,true);
 RETURN jsonb_build_object('lib_id',new_id,'restored',true,'repeated',false);
END $$;

REVOKE ALL ON FUNCTION public.ps_library_history_list_v1(uuid,integer),public.ps_library_history_get_v1(uuid,bigint),
 public.ps_library_archive_conflict_v1(uuid,text,jsonb),public.ps_library_restore_copy_v1(uuid,bigint,uuid) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.ps_library_history_list_v1(uuid,integer),public.ps_library_history_get_v1(uuid,bigint),
 public.ps_library_archive_conflict_v1(uuid,text,jsonb),public.ps_library_restore_copy_v1(uuid,bigint,uuid) TO authenticated;
COMMIT;
