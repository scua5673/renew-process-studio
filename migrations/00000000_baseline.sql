CREATE OR REPLACE FUNCTION public.ps_sched_history_v2(p_wid uuid, p_limit integer DEFAULT 30)
 RETURNS TABLE(id bigint, vlen integer, n_match integer, anchor_monday text, edited_by text, cupd bigint, changed_by uuid, changed_at timestamp with time zone)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  my_role text;
begin
  if not exists (select 1 from public.ps_workspaces w
                 where w.id = p_wid and w.owner_id = auth.uid()) then
    select m.role into my_role
    from public.ps_members m
    where m.workspace_id = p_wid and m.user_id = auth.uid();
    if coalesce(my_role,'') not in ('owner','executive','admin') then
      raise exception 'executives only';
    end if;
  end if;
  return query
  select h.id,
         coalesce(length(h.v),0)::integer,
         coalesce((length(h.v) - length(replace(h.v,'"mid":"','')))/7, 0)::integer,
         substring(h.v from '"anchorMonday":"([^"]+)"'),
         substring(h.v from '"editedBy":"([^"]{1,20})"'),
         h.cupd, h.changed_by, h.changed_at
  from public.ps_kv_history h
  where h.workspace_id = p_wid::text and h.k = 'process_coach_v1' and h.v is not null
  order by h.changed_at desc
  limit greatest(1, least(coalesce(p_limit,30), 100));
end;
$function$;

CREATE OR REPLACE FUNCTION public.ps_sched_write_guard()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  old_anchor date;
  new_anchor date;
  my_role text;
  perms jsonb;
begin
  if new.k <> 'process_coach_v1' then
    return new;
  end if;
  begin
    new_anchor := substring(new.v from '"anchorMonday":"(\d{4}-\d{2}-\d{2})"')::date;
    if tg_op = 'UPDATE' then
      old_anchor := substring(old.v from '"anchorMonday":"(\d{4}-\d{2}-\d{2})"')::date;
    end if;
  exception when others then
    new_anchor := null; old_anchor := null;
  end;
  if old_anchor is not null and new_anchor is not null and new_anchor < old_anchor then
    new.v := old.v; new.cupd := old.cupd;
    return new;
  end if;
  if exists (select 1 from public.ps_workspaces w
             where w.id = new.workspace_id and w.owner_id = auth.uid()) then
    return new;
  end if;
  select m.role into my_role
  from public.ps_members m
  where m.workspace_id = new.workspace_id and m.user_id = auth.uid();
  if my_role in ('owner','executive','admin') then
    return new;
  end if;
  if my_role = 'staff' then
    select k2.v::jsonb into perms
    from public.ps_kv k2
    where k2.workspace_id = new.workspace_id and k2.k = 'cs_perms_v1';
    if coalesce(perms->>'schedEdit','') = 'staff' then
      return new;
    end if;
  end if;
  if tg_op = 'UPDATE' then
    new.v := old.v; new.cupd := old.cupd;
  end if;
  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.ps_scout_registry_guard_v1()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'pg_catalog'
AS $function$
DECLARE previous_document jsonb; next_document jsonb; reason text;
BEGIN
  IF OLD.k IS DISTINCT FROM 'cs_scout_targets_v1' THEN RETURN NEW; END IF;
  BEGIN previous_document:=OLD.v::text::jsonb;
  EXCEPTION WHEN invalid_text_representation THEN RETURN NEW;
  END;
  IF jsonb_typeof(previous_document -> 'scoutRegistry') IS DISTINCT FROM 'object' OR previous_document #> '{scoutRegistry,v}' IS DISTINCT FROM '1'::jsonb THEN RETURN NEW; END IF;
  IF NEW.k IS DISTINCT FROM OLD.k THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='ps_scout_registry_guard_v1: key_change',HINT='Keep this candidate document under its existing key.'; END IF;
  BEGIN next_document:=NEW.v::text::jsonb;
  EXCEPTION WHEN invalid_text_representation THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='ps_scout_registry_guard_v1: invalid_json',HINT='Update PROCESS STUDIO, reload the latest candidate document, and retry.';
  END;
  reason:=public.ps_scout_registry_guard_v1_reason(previous_document,next_document);
  IF reason IS NOT NULL THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='ps_scout_registry_guard_v1: ' || reason,HINT='Update PROCESS STUDIO, reload the latest candidate document, and retry. The server document was not replaced.'; END IF;
  RETURN NEW;
END
$function$;

CREATE OR REPLACE FUNCTION public.ps_scout_registry_guard_v1_array_kept(previous_values jsonb, next_values jsonb)
 RETURNS boolean
 LANGUAGE sql
 IMMUTABLE
 SET search_path TO 'pg_catalog'
AS $function$
  SELECT CASE WHEN jsonb_typeof(previous_values) IS DISTINCT FROM 'array' OR jsonb_typeof(next_values) IS DISTINCT FROM 'array' THEN false ELSE NOT EXISTS (SELECT 1 FROM jsonb_array_elements(previous_values) AS previous(value) WHERE NOT EXISTS (SELECT 1 FROM jsonb_array_elements(next_values) AS next(value) WHERE next.value=previous.value)) END
$function$;

CREATE OR REPLACE FUNCTION public.ps_scout_registry_guard_v1_reason(old_document jsonb, new_document jsonb)
 RETURNS text
 LANGUAGE plpgsql
 IMMUTABLE
 SET search_path TO 'pg_catalog'
AS $function$
DECLARE
  old_registry jsonb := old_document -> 'scoutRegistry';
  new_registry jsonb := new_document -> 'scoutRegistry';
  previous_candidate jsonb; next_candidate jsonb; candidate_id text; field_name text; family text;
  previous_value jsonb; next_value jsonb; previous_array jsonb; next_array jsonb;
  observation jsonb; next_observation jsonb; placement_id text; entry record;
BEGIN
  IF jsonb_typeof(old_registry) IS DISTINCT FROM 'object' OR old_registry -> 'v' IS DISTINCT FROM '1'::jsonb THEN RETURN NULL; END IF;
  IF jsonb_typeof(old_registry -> 'candidates') IS DISTINCT FROM 'object' OR jsonb_typeof(old_registry -> 'meta') IS DISTINCT FROM 'object' OR jsonb_typeof(old_document -> 'players') IS DISTINCT FROM 'array' THEN RETURN 'old_registry_invalid'; END IF;
  IF jsonb_typeof(new_document) IS DISTINCT FROM 'object' OR jsonb_typeof(new_document -> 'players') IS DISTINCT FROM 'array'
     OR (new_document ? 'v' AND new_document -> 'v' <> 'null'::jsonb AND new_document -> 'v' IS DISTINCT FROM '1'::jsonb)
     OR jsonb_typeof(new_registry) IS DISTINCT FROM 'object' OR new_registry -> 'v' IS DISTINCT FROM '1'::jsonb
     OR jsonb_typeof(new_registry -> 'candidates') IS DISTINCT FROM 'object' OR jsonb_typeof(new_registry -> 'meta') IS DISTINCT FROM 'object'
     OR (new_registry -> 'meta' ? 'pointSets' AND new_registry #> '{meta,pointSets}' NOT IN ('null'::jsonb,'false'::jsonb,'0'::jsonb,'""'::jsonb) AND jsonb_typeof(new_registry #> '{meta,pointSets}') IS DISTINCT FROM 'array') THEN RETURN 'registry_missing_or_invalid'; END IF;
  FOR entry IN SELECT key,value FROM jsonb_each(old_registry -> 'candidates') LOOP
    candidate_id:=entry.key; previous_candidate:=entry.value; next_candidate:=new_registry -> 'candidates' -> candidate_id;
    IF jsonb_typeof(previous_candidate) IS DISTINCT FROM 'object' OR jsonb_typeof(previous_candidate -> 'info') IS DISTINCT FROM 'object' THEN RETURN 'old_candidate_invalid'; END IF;
    IF jsonb_typeof(next_candidate) IS DISTINCT FROM 'object' OR next_candidate ->> 'id' IS DISTINCT FROM candidate_id OR jsonb_typeof(next_candidate -> 'info') IS DISTINCT FROM 'object' THEN RETURN 'candidate_missing_or_invalid'; END IF;
    FOREACH family IN ARRAY ARRAY['variants','sourceHistory','scoreHistory'] LOOP
      previous_array:=coalesce(nullif(previous_candidate -> family,'null'::jsonb),'[]'::jsonb); next_array:=coalesce(nullif(next_candidate -> family,'null'::jsonb),'[]'::jsonb);
      IF NOT public.ps_scout_registry_guard_v1_array_kept(previous_array,next_array) THEN RETURN 'candidate_history_removed'; END IF;
    END LOOP;
    previous_value:=previous_candidate -> 'source';
    IF previous_value IS NOT NULL AND previous_value <> 'null'::jsonb AND previous_value IS DISTINCT FROM next_candidate -> 'source' AND NOT public.ps_scout_registry_guard_v1_array_kept(jsonb_build_array(previous_value),coalesce(nullif(next_candidate -> 'sourceHistory','null'::jsonb),'[]'::jsonb)) THEN RETURN 'candidate_source_removed'; END IF;
    IF jsonb_typeof(coalesce(nullif(previous_candidate #> '{info,profile}','null'::jsonb),'{}'::jsonb)) <> 'object' OR jsonb_typeof(coalesce(nullif(next_candidate #> '{info,profile}','null'::jsonb),'{}'::jsonb)) <> 'object' THEN RETURN 'candidate_profile_invalid'; END IF;
    FOR field_name,previous_value IN SELECT key,value FROM jsonb_each((previous_candidate -> 'info') - 'profile') UNION ALL SELECT 'profile.' || key,value FROM jsonb_each(coalesce(nullif(previous_candidate #> '{info,profile}','null'::jsonb),'{}'::jsonb)) LOOP
      IF left(field_name,8)='profile.' THEN next_value:=next_candidate #> ARRAY['info','profile',substr(field_name,9)]; ELSE next_value:=next_candidate #> ARRAY['info',field_name]; END IF;
      IF previous_value IS DISTINCT FROM next_value AND NOT (previous_value IN ('null'::jsonb,'""'::jsonb) AND coalesce(previous_candidate #> ARRAY['edits',field_name],'null'::jsonb)='null'::jsonb)
        AND NOT EXISTS (SELECT 1 FROM jsonb_array_elements(coalesce(nullif(next_candidate -> 'variants','null'::jsonb),'[]'::jsonb)) AS variant(value) WHERE variant.value ->> 'field'=field_name AND variant.value -> 'value'=previous_value) THEN RETURN 'candidate_info_removed'; END IF;
    END LOOP;
    FOREACH family IN ARRAY ARRAY['points','ratings'] LOOP
      IF jsonb_typeof(coalesce(nullif(previous_candidate -> family,'null'::jsonb),'{}'::jsonb)) <> 'object' OR jsonb_typeof(coalesce(nullif(next_candidate -> family,'null'::jsonb),'{}'::jsonb)) <> 'object' THEN RETURN 'candidate_scores_invalid'; END IF;
      FOR field_name,previous_value IN SELECT key,value FROM jsonb_each(coalesce(nullif(previous_candidate -> family,'null'::jsonb),'{}'::jsonb)) LOOP
        IF previous_value IS DISTINCT FROM next_candidate #> ARRAY[family,field_name] AND NOT EXISTS (SELECT 1 FROM jsonb_array_elements(coalesce(nullif(next_candidate -> 'scoreHistory','null'::jsonb),'[]'::jsonb)) AS history(value) WHERE history.value ->> 'kind'=family AND history.value ->> 'key'=field_name AND history.value -> 'value'=previous_value) THEN RETURN 'candidate_score_removed'; END IF;
      END LOOP;
    END LOOP;
  END LOOP;
  previous_array:=coalesce(nullif(old_registry -> 'metaHistory','null'::jsonb),'[]'::jsonb); next_array:=coalesce(nullif(new_registry -> 'metaHistory','null'::jsonb),'[]'::jsonb);
  IF NOT public.ps_scout_registry_guard_v1_array_kept(previous_array,next_array) THEN RETURN 'metadata_history_removed'; END IF;
  IF old_registry -> 'meta' IS DISTINCT FROM new_registry -> 'meta' AND NOT public.ps_scout_registry_guard_v1_array_kept(jsonb_build_array(old_registry -> 'meta'),next_array) THEN RETURN 'metadata_source_removed'; END IF;
  IF jsonb_typeof(coalesce(nullif(old_registry -> 'placementHistory','null'::jsonb),'{}'::jsonb)) <> 'object' OR jsonb_typeof(coalesce(nullif(new_registry -> 'placementHistory','null'::jsonb),'{}'::jsonb)) <> 'object' THEN RETURN 'placement_history_invalid'; END IF;
  FOR entry IN SELECT key,value FROM jsonb_each(coalesce(nullif(old_registry -> 'placementHistory','null'::jsonb),'{}'::jsonb)) LOOP
    IF NOT public.ps_scout_registry_guard_v1_array_kept(entry.value,coalesce(nullif(new_registry #> ARRAY['placementHistory',entry.key],'null'::jsonb),'[]'::jsonb)) THEN RETURN 'placement_history_removed'; END IF;
  END LOOP;
  FOR entry IN SELECT value FROM jsonb_array_elements(old_document -> 'players') LOOP
    placement_id:=entry.value ->> 'id'; IF placement_id IS NULL THEN RETURN 'old_placement_invalid'; END IF;
    observation:=entry.value - ARRAY['name','num','foot','club','grade','id','type','profile','_scoutRef'];
    SELECT p.value - ARRAY['name','num','foot','club','grade','id','type','profile','_scoutRef'] INTO next_observation FROM jsonb_array_elements(new_document -> 'players') AS p(value) WHERE p.value ->> 'id'=placement_id LIMIT 1;
    IF observation IS DISTINCT FROM next_observation AND NOT public.ps_scout_registry_guard_v1_array_kept(jsonb_build_array(observation),coalesce(nullif(new_registry #> ARRAY['placementHistory',placement_id],'null'::jsonb),'[]'::jsonb)) THEN RETURN 'placement_observation_removed'; END IF;
  END LOOP;
  RETURN NULL;
END
$function$;

