CREATE OR REPLACE FUNCTION public.ps_claim_player(p_wid uuid, p_player_id text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare pj jsonb; uid text; taken text; role text; me jsonb;
begin
  if not public.ps_is_member(p_wid) then raise exception 'not a member'; end if;
  if p_player_id is null or btrim(p_player_id) = '' then raise exception 'player required'; end if;
  uid := auth.uid()::text;
  begin select v::jsonb into pj from public.ps_kv where workspace_id=p_wid and k='cs_perms_v1' limit 1;
  exception when others then pj := null; end;
  pj := coalesce(pj, '{"defaultRole":"player","members":{}}'::jsonb);
  if jsonb_typeof(pj->'members') is distinct from 'object' then
    pj := jsonb_set(pj,'{members}','{}'::jsonb,true);
  end if;
  select e.key into taken from jsonb_each(pj->'members') e
   where e.value->>'playerId' = p_player_id and e.key <> uid limit 1;
  if taken is not null then raise exception 'already claimed'; end if;
  me   := coalesce(pj #> array['members',uid], '{}'::jsonb);
  role := coalesce(me->>'role', pj->>'defaultRole', 'player');
  pj := jsonb_set(pj, array['members',uid],
        me || jsonb_build_object('role',role,'playerId',p_player_id,
                                 'claimedBy','self',
                                 'claimedAt',(extract(epoch from clock_timestamp())*1000)::bigint), true);
  insert into public.ps_kv(workspace_id,k,v,cupd)
    values (p_wid,'cs_perms_v1',pj::text,(extract(epoch from clock_timestamp())*1000)::bigint)
  on conflict (workspace_id,k) do update set v=excluded.v, cupd=excluded.cupd;
  return pj;
end $function$;

