CREATE OR REPLACE FUNCTION public.ps_1644_json_truthy(p_value jsonb)
 RETURNS boolean
 LANGUAGE sql
 IMMUTABLE PARALLEL SAFE
 SET search_path TO 'pg_catalog'
AS $function$
  select case jsonb_typeof(p_value)
    when 'null'    then false
    when 'boolean' then coalesce((p_value #>> '{}')::boolean, false)
    when 'number'  then coalesce((p_value #>> '{}')::numeric <> 0, false)
    when 'string'  then coalesce(p_value #>> '{}', '') <> ''
    when 'array'   then true
    when 'object'  then true
    else false
  end;
$function$;

CREATE OR REPLACE FUNCTION public.ps_1644_lineage_guard()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
declare
  uid              uuid := auth.uid();
  jwt_role         text := coalesce(auth.role(), '');
  row_already_here boolean := false;
  old_doc          jsonb;
  new_doc          jsonb;
  schedule_doc     jsonb;
  perms            jsonb;
  my_role          text;
  is_owner         boolean := false;
  schedule_allowed boolean := false;
  old_rev          bigint;
  new_rev          bigint;
  new_base_rev     bigint;
  old_rev_text     text;
  new_rev_text     text;
  new_base_rev_text text;
  old_rev_invalid  boolean := false;
  old_token        text;
  new_token        text;
  new_base_token   text;
  structure_ok     boolean := false;
begin
  if uid is null then
    -- SECURITY DEFINER의 current_user는 함수 소유자라 신뢰 근거가 될 수 없다.
    -- 원래 접속 역할(session_user) 또는 검증된 JWT service_role만 운영 우회로 인정한다.
    if jwt_role = 'service_role'
       or (jwt_role = '' and session_user in ('postgres', 'supabase_admin')) then
      return new;
    end if;
    return null; -- anon/auth 정보 없는 PostgREST 요청은 우회하지 않는다
  end if;

  -- 같은 v를 이용해 보호 행의 PK 신원을 바꾸는 우회를 멱등 빠른 반환보다 먼저 막는다.
  if tg_op = 'UPDATE'
     and (new.workspace_id is distinct from old.workspace_id
          or new.k is distinct from old.k) then
    return null;
  end if;
  if new.k not in ('process_coach_v1', 'cs_team_matches_v1') then
    return new;
  end if;

  -- 일정 권한은 관찰 모드(ps_guard_mode.enforce=false)와 RLS에 기대지 않고
  -- lineage 가 INSERT/UPDATE 모두 직접 fail-closed로 강제한다.
  -- 응답 유실의 같은 원문 재시도도 이 검사를 먼저 통과해야 한다.
  if new.k = 'process_coach_v1' then
    select exists (
      select 1 from public.ps_workspaces w
      where w.id = new.workspace_id and w.owner_id = uid
    ) into is_owner;
    begin
      select k.v::jsonb into perms
      from public.ps_kv k
      where k.workspace_id = new.workspace_id and k.k = 'cs_perms_v1';
    exception when others then
      perms := null;
    end;
    my_role := coalesce(
      perms -> 'members' -> (uid::text) ->> 'role',
      perms ->> 'defaultRole',
      'player'
    );
    schedule_allowed := coalesce(is_owner, false)
      or my_role in ('admin', 'executive')
      or (my_role = 'staff' and coalesce(perms ->> 'schedEdit', '') = 'staff');
    if not schedule_allowed then
      perform public.ps_kv_note_denied(new.workspace_id, uid, new.k,
        '일정은 운영진만 편집할 수 있습니다');
      return null;
    end if;
  end if;

  -- PostgREST upsert는 기존 행이어도 먼저 BEFORE INSERT를 거친다.
  -- 충돌 후보가 이미 있으면 INSERT 단계에서는 통과시키고 실제 BEFORE UPDATE에서 검사한다.
  if tg_op = 'INSERT' then
    select exists (
      select 1 from public.ps_kv k
      where k.workspace_id = new.workspace_id and k.k = new.k
    ) into row_already_here;
    if row_already_here then
      return new;
    end if;
  end if;

  -- 응답을 잃은 같은 원문 재전송은 무해한 멱등 재시도다.
  if tg_op = 'UPDATE' and new.v = old.v then
    new.cupd := old.cupd;
    return new;
  end if;

  begin
    new_doc := new.v::jsonb;
    if tg_op = 'UPDATE' then old_doc := old.v::jsonb; else old_doc := '{}'::jsonb; end if;
  exception when others then
    perform public.ps_kv_note_denied(new.workspace_id, uid, new.k,
      '1.644 서버 검증: JSON을 읽지 못해 저장하지 않았습니다');
    return null;
  end;

  if new.k = 'process_coach_v1' then
    begin
      new_rev_text := btrim(coalesce(new_doc ->> 'scheduleRev', ''));
      new_base_rev_text := btrim(coalesce(new_doc ->> 'scheduleBaseRev', ''));
      if new_rev_text ~ '^[0-9]+$' then new_rev := new_rev_text::bigint; else new_rev := null; end if;
      if new_base_rev_text ~ '^[0-9]+$' then new_base_rev := new_base_rev_text::bigint; else new_base_rev := null; end if;
      new_token := nullif(new_doc ->> 'scheduleToken', '');
      new_base_token := coalesce(new_doc ->> 'scheduleBaseToken', '');
      if tg_op = 'UPDATE' then
        old_rev_text := btrim(coalesce(old_doc ->> 'scheduleRev', ''));
        if old_rev_text = '' then
          old_rev := 0; -- legacy 일정의 첫 1.644 커밋: rev=1/baseRev=0
        elsif old_rev_text ~ '^[0-9]+$' then
          old_rev := old_rev_text::bigint;
        else
          old_rev_invalid := true; old_rev := null; -- 명시적 비숫자 값은 손상으로 거부
        end if;
        old_token := nullif(old_doc ->> 'scheduleToken', '');
      else
        old_rev := 0;
        old_token := null;
      end if;
      structure_ok := public.ps_1644_schedule_structure_ok(new_doc);
    exception when others then
      new_rev := null; new_base_rev := null; new_token := null;
      old_rev := null; old_token := null; old_rev_invalid := true; structure_ok := false;
    end;

    if not structure_ok
       or old_rev_invalid
       or old_rev is null
       or new_rev is null
       or new_base_rev is null
       or new_rev <> old_rev + 1
       or new_base_rev <> old_rev
       or new_base_token is distinct from coalesce(old_token, '')
       or new_token is null
       or length(new_token) < 16
       or length(new_token) > 128
       or new_token !~ '^[A-Za-z0-9._:-]+$'
       or new_token is not distinct from old_token then
      perform public.ps_kv_note_denied(new.workspace_id, uid, new.k,
        '오래된 일정 판본이 최신 일정을 덮으려 했습니다 — 1.644로 새로고침하세요');
      return null;
    end if;

    return new;
  end if;

  -- cs_team_matches_v1: 현재 서버 일정 한 행만 정본으로 사용한다.
  begin
    select k.v::jsonb into schedule_doc
    from public.ps_kv k
    where k.workspace_id = new.workspace_id and k.k = 'process_coach_v1';
  exception when others then
    schedule_doc := null;
  end;

  if schedule_doc is null then
    -- 일정이 아직 없는 공간에서는 sourceId 없는 수동 경기만 허용한다.
    schedule_doc := jsonb_build_object('anchorMonday', '1970-01-05', 'weeks', '{}'::jsonb);
  end if;

  if not public.ps_1644_matches_canonical_ok(old_doc, new_doc, schedule_doc) then
    perform public.ps_kv_note_denied(new.workspace_id, uid, new.k,
      '경기 날짜·상대·시간이 최신 일정과 달라 저장을 보류했습니다 — 먼저 일정을 동기화하세요');
    return null;
  end if;

  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.ps_1644_matches_canonical_ok(p_old_doc jsonb, p_new_doc jsonb, p_schedule_doc jsonb)
 RETURNS boolean
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
declare
  old_matches jsonb;
  new_matches jsonb;
  hidden_sched jsonb;
begin
  if p_new_doc is null or jsonb_typeof(p_new_doc) <> 'object' then
    return false;
  end if;
  if not public.ps_1644_schedule_structure_ok(p_schedule_doc) then
    return false;
  end if;
  if jsonb_typeof(p_new_doc -> 'matches') <> 'array' then
    return false;
  end if;

  old_matches := case
    when jsonb_typeof(p_old_doc -> 'matches') = 'array' then p_old_doc -> 'matches'
    else '[]'::jsonb
  end;
  new_matches := p_new_doc -> 'matches';
  hidden_sched := case
    when jsonb_typeof(p_new_doc -> 'hiddenSched') = 'array' then p_new_doc -> 'hiddenSched'
    else '[]'::jsonb
  end;

  -- 일정 자체에 같은 mid가 두 칸 있으면 어느 날짜가 정규값인지 정할 수 없다.
  if exists (
    select 1
    from public.ps_1644_schedule_links(p_schedule_doc) l
    group by l.source_id
    having count(*) > 1
  ) then
    return false;
  end if;

  -- 현재 일정에 살아 있는 sourceId는 경기 문서에서도 하나만 있어야 한다.
  if exists (
    select 1
    from jsonb_array_elements(new_matches) n(item)
    join public.ps_1644_schedule_links(p_schedule_doc) l
      on l.source_id = n.item ->> 'sourceId'
    group by n.item ->> 'sourceId'
    having count(*) > 1
  ) then
    return false;
  end if;

  -- 현재 일정에 연결된 경기의 날짜/시간/상대는 일정이 정본이다.
  -- 일정 상대가 비어 있을 때만 기존 경기 화면의 알려진 상대 이름을 허용한다.
  if exists (
    select 1
    from jsonb_array_elements(new_matches) n(item)
    join public.ps_1644_schedule_links(p_schedule_doc) l
      on l.source_id = n.item ->> 'sourceId'
    where coalesce(n.item ->> 'date', '') is distinct from l.match_date
       or btrim(coalesce(n.item ->> 'time', '')) is distinct from l.match_time
       or (
         l.opponent <> ''
         and public.ps_1644_schedule_text(n.item ->> 'opponent') is distinct from l.opponent
       )
  ) then
    return false;
  end if;

  -- OLD에 있던 현재 일정 경기의 행을 조용히 없애지 못한다.
  -- 사용자가 경기 기록 삭제를 명시한 hiddenSched tombstone(sid)은 예외다.
  if exists (
    select 1
    from jsonb_array_elements(old_matches) o(item)
    join public.ps_1644_schedule_links(p_schedule_doc) l
      on l.source_id = o.item ->> 'sourceId'
    where not exists (
      select 1
      from jsonb_array_elements(new_matches) n(item)
      where n.item ->> 'sourceId' = l.source_id
    )
    and not exists (
      select 1
      from jsonb_array_elements(hidden_sched) h(item)
      where h.item ->> 'sid' = l.source_id
    )
  ) then
    return false;
  end if;

  -- 현재 일정에도 OLD에도 없던 sched:* 행은 낡은 기기의 부활로 본다.
  -- sourceId가 없는 수동 경기와 OLD에 이미 있던 역사적 unlinked 행은 그대로 허용한다.
  if exists (
    select 1
    from jsonb_array_elements(new_matches) n(item)
    where coalesce(n.item ->> 'sourceId', '') like 'sched:%'
      and not exists (
        select 1
        from public.ps_1644_schedule_links(p_schedule_doc) l
        where l.source_id = n.item ->> 'sourceId'
      )
      and not exists (
        select 1
        from jsonb_array_elements(old_matches) o(item)
        where o.item ->> 'sourceId' = n.item ->> 'sourceId'
      )
  ) then
    return false;
  end if;

  return true;
exception when others then
  -- 깨진 JSON/날짜/주차 키를 '검사 실패지만 허용'으로 만들지 않는다.
  return false;
end;
$function$;

CREATE OR REPLACE FUNCTION public.ps_1644_schedule_links(p_doc jsonb)
 RETURNS TABLE(source_id text, match_date text, opponent text, match_time text)
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
  with cfg as (
    select (p_doc ->> 'anchorMonday')::date as anchor_monday, p_doc -> 'weeks' as weeks
  ), day_rows as (
    select
      c.anchor_monday,
      w.key::integer as week_no,
      (d.ordinality - 1)::integer as day_no,
      d.day
    from cfg c
    cross join lateral jsonb_each(c.weeks) w
    cross join lateral jsonb_array_elements(w.value) with ordinality d(day, ordinality)
  ), parts as (
    select d.*,
      case
        when public.ps_1644_json_truthy(d.day #> '{match,data}') then d.day #> '{match,data}'
        when public.ps_1644_json_truthy(d.day #> '{match,details}') then d.day #> '{match,details}'
        else '{}'::jsonb
      end as md,
      case
        when public.ps_1644_json_truthy(d.day #> '{board,data}') then d.day #> '{board,data}'
        when public.ps_1644_json_truthy(d.day #> '{board,details}') then d.day #> '{board,details}'
        else '{}'::jsonb
      end as bd
    from day_rows d
  )
  select
    'sched:' || (p.day ->> 'mid') as source_id,
    to_char(p.anchor_monday + (p.week_no * 7 + p.day_no), 'YYYY-MM-DD') as match_date,
    coalesce(
      nullif(public.ps_1644_schedule_text(p.day #>> '{match,opp}'), ''),
      nullif(public.ps_1644_schedule_text(p.day #>> '{match,opponent}'), ''),
      nullif(public.ps_1644_schedule_text(p.day #>> '{match,opponentName}'), ''),
      nullif(public.ps_1644_schedule_text(p.day #>> '{match,vs}'), ''),
      nullif(public.ps_1644_schedule_text(p.day #>> '{match,matchOpp}'), ''),
      nullif(public.ps_1644_schedule_text(p.day #>> '{match,matchOpponent}'), ''),
      nullif(public.ps_1644_schedule_text(p.day #>> '{match,team}'), ''),
      nullif(public.ps_1644_schedule_text(p.day #>> '{match,awayTeam}'), ''),
      nullif(public.ps_1644_schedule_text(p.day #>> '{match,homeTeam}'), ''),
      nullif(public.ps_1644_schedule_text(p.day #>> '{match,name}'), ''),
      nullif(public.ps_1644_schedule_text(p.day #>> '{match,title}'), ''),
      nullif(public.ps_1644_schedule_text(p.day #>> '{match,label}'), ''),
      nullif(public.ps_1644_schedule_text(p.day #>> '{match,summary}'), ''),
      nullif(public.ps_1644_schedule_text(p.md ->> 'opp'), ''),
      nullif(public.ps_1644_schedule_text(p.md ->> 'opponent'), ''),
      nullif(public.ps_1644_schedule_text(p.md ->> 'opponentName'), ''),
      nullif(public.ps_1644_schedule_text(p.md ->> 'vs'), ''),
      nullif(public.ps_1644_schedule_text(p.md ->> 'team'), ''),
      nullif(public.ps_1644_schedule_text(p.md ->> 'name'), ''),
      nullif(public.ps_1644_schedule_text(p.md ->> 'title'), ''),
      nullif(public.ps_1644_schedule_text(p.day #>> '{board,opp}'), ''),
      nullif(public.ps_1644_schedule_text(p.day #>> '{board,opponent}'), ''),
      nullif(public.ps_1644_schedule_text(p.day #>> '{board,opponentName}'), ''),
      nullif(public.ps_1644_schedule_text(p.day #>> '{board,vs}'), ''),
      nullif(public.ps_1644_schedule_text(p.day #>> '{board,matchOpp}'), ''),
      nullif(public.ps_1644_schedule_text(p.day #>> '{board,matchOpponent}'), ''),
      nullif(public.ps_1644_schedule_text(p.day #>> '{board,team}'), ''),
      nullif(public.ps_1644_schedule_text(p.day #>> '{board,awayTeam}'), ''),
      nullif(public.ps_1644_schedule_text(p.day #>> '{board,homeTeam}'), ''),
      nullif(public.ps_1644_schedule_text(p.day #>> '{board,title}'), ''),
      nullif(public.ps_1644_schedule_text(p.day #>> '{board,label}'), ''),
      nullif(public.ps_1644_schedule_text(p.bd ->> 'opp'), ''),
      nullif(public.ps_1644_schedule_text(p.bd ->> 'opponent'), ''),
      nullif(public.ps_1644_schedule_text(p.bd ->> 'opponentName'), ''),
      nullif(public.ps_1644_schedule_text(p.bd ->> 'vs'), ''),
      nullif(public.ps_1644_schedule_text(p.bd ->> 'team'), ''),
      nullif(public.ps_1644_schedule_text(p.bd ->> 'name'), ''),
      nullif(public.ps_1644_schedule_text(p.bd ->> 'title'), ''),
      nullif(public.ps_1644_schedule_text(p.day ->> 'opp'), ''),
      nullif(public.ps_1644_schedule_text(p.day ->> 'opponent'), ''),
      nullif(public.ps_1644_schedule_text(p.day ->> 'opponentName'), ''),
      nullif(public.ps_1644_schedule_text(p.day ->> 'vs'), ''),
      nullif(public.ps_1644_schedule_text(p.day ->> 'matchOpp'), ''),
      nullif(public.ps_1644_schedule_text(p.day ->> 'matchOpponent'), ''),
      nullif(public.ps_1644_schedule_text(p.day ->> 'awayTeam'), ''),
      nullif(public.ps_1644_schedule_text(p.day ->> 'homeTeam'), ''),
      nullif(public.ps_1644_schedule_text(p.day ->> 'title'), ''),
      ''
    ) as opponent,
    btrim(coalesce(
      nullif(p.day #>> '{match,time}', ''),
      nullif(p.day #>> '{match,kickoff}', ''),
      nullif(p.day #>> '{board,time}', ''),
      nullif(p.day #>> '{board,kickoff}', ''),
      p.day ->> 'time',
      ''
    )) as match_time
  from parts p
  where btrim(coalesce(p.day ->> 'mid', '')) <> ''
    and (
      public.ps_1644_json_truthy(p.day -> 'match')
      or p.day #>> '{board,sched}' = '경기'
      or p.day #>> '{board,type}' = '경기'
      or p.day #>> '{board,kind}' = 'match'
    );
$function$;

CREATE OR REPLACE FUNCTION public.ps_1644_schedule_structure_ok(p_doc jsonb)
 RETURNS boolean
 LANGUAGE plpgsql
 IMMUTABLE SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
declare
  anchor_date date;
  week_row record;
  day_row record;
  is_match boolean;
  week_no integer;
begin
  if p_doc is null or jsonb_typeof(p_doc) <> 'object' then return false; end if;
  if coalesce(p_doc ->> 'anchorMonday', '') !~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' then return false; end if;
  anchor_date := (p_doc ->> 'anchorMonday')::date;
  if extract(isodow from anchor_date) <> 1 then return false; end if;
  if jsonb_typeof(p_doc -> 'weeks') <> 'object' then return false; end if;

  for week_row in select e.key, e.value from jsonb_each(p_doc -> 'weeks') e loop
    if week_row.key !~ '^-?[0-9]+$' or length(week_row.key) > 6 then return false; end if;
    week_no := week_row.key::integer; -- 범위를 포함한 실제 cast 검증
    if week_row.key <> week_no::text then return false; end if; -- 01/-0 같은 겹치는 별칭 금지
    if jsonb_typeof(week_row.value) <> 'array'
       or jsonb_array_length(week_row.value) <> 7 then return false; end if;

    for day_row in select d.value from jsonb_array_elements(week_row.value) d loop
      if jsonb_typeof(day_row.value) <> 'object' then return false; end if;
      is_match := public.ps_1644_json_truthy(day_row.value -> 'match')
        or day_row.value #>> '{board,sched}' = '경기'
        or day_row.value #>> '{board,type}' = '경기'
        or day_row.value #>> '{board,kind}' = 'match';
      if is_match and (
        jsonb_typeof(day_row.value -> 'mid') is distinct from 'string'
        or btrim(coalesce(day_row.value ->> 'mid', '')) = ''
      ) then return false; end if;
      if day_row.value ? 'mid'
         and day_row.value -> 'mid' <> 'null'::jsonb
         and (
           jsonb_typeof(day_row.value -> 'mid') is distinct from 'string'
           or btrim(coalesce(day_row.value ->> 'mid', '')) = ''
         ) then return false; end if;
    end loop;
  end loop;

  -- 경기 여부와 무관하게 문서 안의 모든 실제 mid는 유일해야 한다.
  if exists (
    select 1
    from jsonb_each(p_doc -> 'weeks') w
    cross join lateral jsonb_array_elements(w.value) d(day)
    where jsonb_typeof(d.day -> 'mid') = 'string'
      and btrim(coalesce(d.day ->> 'mid', '')) <> ''
    group by d.day ->> 'mid'
    having count(*) > 1
  ) then return false; end if;

  return true;
exception when others then
  return false;
end;
$function$;

CREATE OR REPLACE FUNCTION public.ps_1644_schedule_text(p_value text)
 RETURNS text
 LANGUAGE sql
 IMMUTABLE PARALLEL SAFE
