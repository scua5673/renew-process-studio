CREATE OR REPLACE FUNCTION public.ps_admin_recent_activity(p_days integer DEFAULT 7, p_limit integer DEFAULT 200, p_wid uuid DEFAULT NULL::uuid, p_uid uuid DEFAULT NULL::uuid)
 RETURNS TABLE(at timestamp with time zone, user_id uuid, email text, name text, workspace_id uuid, ws_name text, k text, action text, bytes integer)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if not public.ps_is_admin() then raise exception 'admin only'; end if;
  -- security-v2 를 아직 안 깐 프로젝트에서도 화면이 깨지지 않게 — 빈 결과로 돌려준다.
  if to_regclass('public.ps_audit') is null then return; end if;

  return query
  select a.at,
         a.user_id,
         u.email::text,
         -- ps_members.name 은 설치 시점에 따라 없을 수 있다(ps_admin_members 와 같은 방어).
         nullif(btrim(coalesce(to_jsonb(m) ->> 'name', '')), '')::text,
         a.workspace_id,
         w.name::text,
         a.k::text,
         a.action::text,
         a.bytes
  from public.ps_audit a
  left join auth.users u          on u.id = a.user_id
  left join public.ps_members m   on m.workspace_id = a.workspace_id and m.user_id = a.user_id
  left join public.ps_workspaces w on w.id = a.workspace_id
  where a.at > now() - make_interval(days => greatest(1, coalesce(p_days, 7)))
    and (p_wid is null or a.workspace_id = p_wid)
    and (p_uid is null or a.user_id = p_uid)
  order by a.at desc
  limit greatest(1, least(coalesce(p_limit, 200), 1000));
end $function$;

CREATE OR REPLACE FUNCTION public.ps_admin_remove_member(p_wid uuid, p_uid uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
