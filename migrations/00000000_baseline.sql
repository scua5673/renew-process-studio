CREATE OR REPLACE FUNCTION public.ps_comm_like(pid text)
 RETURNS TABLE(liked boolean, likes integer)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare _uid uuid := auth.uid(); _has boolean; _cnt int;
begin
  if _uid is null then raise exception 'auth required'; end if;
  select true into _has from public.ps_comm_likes where pub_id = pid and uid = _uid;
  if _has then
    delete from public.ps_comm_likes where pub_id = pid and uid = _uid;
    update public.ps_community c set likes = greatest(0, c.likes - 1) where c.id = pid returning c.likes into _cnt;
    liked := false;
  else
    insert into public.ps_comm_likes(pub_id, uid) values (pid, _uid) on conflict do nothing;
    update public.ps_community c set likes = c.likes + 1 where c.id = pid returning c.likes into _cnt;
    liked := true;
  end if;
  likes := coalesce(_cnt, 0);
  return next;
end $function$;

