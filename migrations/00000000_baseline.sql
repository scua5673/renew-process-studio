CREATE OR REPLACE FUNCTION public.ps_support_reply(p_id uuid, p_report_id uuid, p_body text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog'
AS $function$
DECLARE actor uuid:=auth.uid(); admin boolean; report public.ps_support_reports%ROWTYPE; r public.ps_support_replies%ROWTYPE;
  body_value text:=btrim(p_body,E' \t\n\r\f\013'); inserted boolean;
BEGIN
  IF actor IS NULL THEN RAISE EXCEPTION USING ERRCODE='42501',MESSAGE='login_required'; END IF;
  IF p_id IS NULL OR p_report_id IS NULL OR body_value IS NULL OR char_length(body_value) NOT BETWEEN 1 AND 4000 THEN RAISE EXCEPTION USING ERRCODE='22023',MESSAGE='invalid_reply'; END IF;
  admin:=public.ps_is_admin() IS TRUE;
  SELECT * INTO report FROM public.ps_support_reports WHERE id=p_report_id AND (reporter_id=actor OR admin) FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='PT404',MESSAGE='report_not_found'; END IF;
  INSERT INTO public.ps_support_replies(id,report_id,actor_id,author_role,body)
    VALUES(p_id,p_report_id,actor,CASE WHEN admin THEN 'admin' ELSE 'reporter' END,body_value) ON CONFLICT(id) DO NOTHING;
  inserted:=FOUND;
  SELECT * INTO r FROM public.ps_support_replies WHERE id=p_id;
  IF r.actor_id IS DISTINCT FROM actor OR r.report_id IS DISTINCT FROM p_report_id OR r.body IS DISTINCT FROM body_value THEN
    RAISE EXCEPTION USING ERRCODE='PT409',MESSAGE='reply_id_conflict';
  END IF;
  IF inserted THEN
    UPDATE public.ps_support_reports SET updated_at=clock_timestamp(),
      status=CASE WHEN r.author_role='reporter' THEN 'open' ELSE status END,
      closed_at=CASE WHEN r.author_role='reporter' THEN NULL ELSE closed_at END
      WHERE id=p_report_id;
  END IF;
  RETURN (to_jsonb(r)-'actor_id')||jsonb_build_object('is_own',true);
END $function$;

CREATE OR REPLACE FUNCTION public.ps_support_reporter(p_user uuid)
 RETURNS jsonb
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'pg_catalog'
AS $function$
  SELECT jsonb_strip_nulls(jsonb_build_object(
    'user_id',u.id,
    'email',left(nullif(btrim(u.email::text),''),120),
    'name',left(coalesce(mn.name,
      CASE WHEN jsonb_typeof(u.raw_user_meta_data->'name')='string' THEN nullif(btrim(u.raw_user_meta_data->>'name'),'') END,
      CASE WHEN jsonb_typeof(u.raw_user_meta_data->'full_name')='string' THEN nullif(btrim(u.raw_user_meta_data->>'full_name'),'') END,
      CASE WHEN jsonb_typeof(u.raw_user_meta_data->'nickname')='string' THEN nullif(btrim(u.raw_user_meta_data->>'nickname'),'') END,
      CASE WHEN jsonb_typeof(u.raw_user_meta_data->'display_name')='string' THEN nullif(btrim(u.raw_user_meta_data->>'display_name'),'') END,
      CASE WHEN jsonb_typeof(u.raw_user_meta_data->'user_name')='string' THEN nullif(btrim(u.raw_user_meta_data->>'user_name'),'') END),60),
    'teams',coalesce(tm.teams,'[]'::jsonb)))
  FROM auth.users u
  LEFT JOIN LATERAL (
    SELECT min(nullif(btrim(m.name),'')) AS name FROM public.ps_members m WHERE m.user_id=u.id
  ) mn ON true
  LEFT JOIN LATERAL (
    SELECT jsonb_agg(jsonb_build_object('name',left(coalesce(nullif(btrim(w.name),''),'(이름 없는 팀)'),60),'role',m.role) ORDER BY w.name,w.id) AS teams
    FROM public.ps_members m JOIN public.ps_workspaces w ON w.id=m.workspace_id
    WHERE m.user_id=u.id AND w.kind='team'
  ) tm ON true
  WHERE u.id=p_user
$function$;

