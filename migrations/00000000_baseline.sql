CREATE OR REPLACE FUNCTION public.ps_support_create(p_id uuid, p_title text, p_body text, p_diagnostics jsonb DEFAULT '{}'::jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog'
