 SET search_path TO 'public', 'pg_catalog'
AS $function$
DECLARE
  d int := greatest(1, least(coalesce(p_days, 56), 90));
  scan int := least(greatest(1, least(coalesce(p_days, 56), 90)), 14);   -- 자동 감지는 2주까지만(문서 해석 비용)
