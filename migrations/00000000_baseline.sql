CREATE OR REPLACE FUNCTION public.ps_kv_history_trim()
 RETURNS TABLE(collapsed integer, blanked integer, deleted integer)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  c1 integer := 0; c2 integer := 0; c3 integer := 0;
begin
  with t as (
    select id,
      lag(changed_at) over (partition by workspace_id,k order by changed_at, id) prev_at,
      lag(changed_by) over (partition by workspace_id,k order by changed_at, id) prev_by,
      changed_at, changed_by, operation
    from public.ps_kv_history
  )
  delete from public.ps_kv_history h
  using t
  where h.id = t.id and t.operation = 'update'
    and t.prev_at is not null and t.prev_at > t.changed_at - interval '10 minutes'
    and t.prev_by is not distinct from t.changed_by;
  get diagnostics c1 = row_count;
  update public.ps_kv_history set v = null
  where v is not null and changed_at < now() - interval '30 days';
  get diagnostics c2 = row_count;
  delete from public.ps_kv_history where changed_at < now() - interval '90 days';
  get diagnostics c3 = row_count;
  return query select c1, c2, c3;
end;
$function$;

