CREATE OR REPLACE FUNCTION public.ps_kv_build_guard()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare pol record; b text; why text;
begin
  select * into pol from public.ps_app_policy where id=1;
  if not found then return new; end if;
  b := public.ps_request_build();
  if b is null then
    if not pol.block_unversioned then return new; end if;
    why := coalesce(nullif(pol.note,''),'앱을 다시 열어 새 판으로 올려 주세요')||' (판을 알 수 없음)';
  elsif public.ps_build_lt(b, pol.min_build) then
    why := coalesce(nullif(pol.note,''),'앱을 다시 열어 새 판으로 올려 주세요')||' (판 '||b||' < '||pol.min_build||')';
  else
    return new;
  end if;
  begin perform public.ps_kv_note_denied(new.workspace_id, auth.uid(), new.k, why); exception when others then null; end;
  if tg_op = 'UPDATE' then return old; end if;
  return null;
end $function$;

