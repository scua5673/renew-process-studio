CREATE OR REPLACE FUNCTION public.ps_kv_scout_record_guard()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare o jsonb; n jsonb; k text; why text;
begin
  if new.k is distinct from 'scout_tool_v1' then return new; end if;
  begin o:=old.v::jsonb; n:=new.v::jsonb; exception when others then return new; end;
  if jsonb_typeof(o)<>'object' or jsonb_typeof(n)<>'object' then return new; end if;
  foreach k in array array['statusRuns','participationDays','injuryInfo'] loop
    if jsonb_typeof(o->'meta'->k)='object' and o->'meta'->k<>'{}'::jsonb
       and not (coalesce(n->'meta','{}'::jsonb) ? k) then
      why:='선수단 기록('||k||')이 빠진 저장을 막았어요 — 옛 판 앱이 부팅하며 빈 문서를 올린 것으로 보여요. 앱을 새로고침하면 팀 것으로 맞춰져요';
      exit;
    end if;
  end loop;
  /* 배열이 아니면 길이 0 으로 본다(jsonb_array_length 는 배열 아닌 값에서 오류를 낸다 — OR/AND 는 짧게 끊긴다는 보장이 없다) */
  if why is null
     and (case when jsonb_typeof(o->'attrs')='array' then jsonb_array_length(o->'attrs') else 0 end)>0
     and (case when jsonb_typeof(o->'positions')='array' then jsonb_array_length(o->'positions') else 0 end)>0
     and ((case when jsonb_typeof(n->'attrs')='array' then jsonb_array_length(n->'attrs') else 0 end)=0
          or (case when jsonb_typeof(n->'positions')='array' then jsonb_array_length(n->'positions') else 0 end)=0) then
    why:='평가표·포지션이 빈 선수단 저장을 막았어요 — 옛 판 앱이 부팅하며 빈 문서를 올린 것으로 보여요. 앱을 새로고침하면 팀 것으로 맞춰져요';
  end if;
  if why is null then return new; end if;
  begin perform public.ps_kv_note_denied(new.workspace_id, auth.uid(), new.k, why); exception when others then null; end;
  return old;
end $function$;

CREATE OR REPLACE FUNCTION public.ps_kv_scout_record_merge()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_catalog'
AS $function$
DECLARE
  o jsonb; n jsonb; om jsonb; nm jsonb; r jsonb;
  runs_lost int := 0; run_players int := 0; days_lost int := 0; inj_lost int := 0;
  note text;
BEGIN
  IF new.k IS DISTINCT FROM 'scout_tool_v1' OR new.v IS NOT DISTINCT FROM old.v THEN RETURN new; END IF;
  BEGIN
    o := old.v::jsonb; n := new.v::jsonb;
    IF jsonb_typeof(o) IS DISTINCT FROM 'object' OR jsonb_typeof(n) IS DISTINCT FROM 'object'
       OR jsonb_typeof(n->'meta') IS DISTINCT FROM 'object' THEN RETURN new; END IF;
    om := public.ps_srm_obj(o->'meta'); nm := n->'meta';

    IF jsonb_typeof(om->'statusRuns')='object' AND jsonb_typeof(nm->'statusRuns')='object' THEN
      r := public.ps_srm_merge_runs(om->'statusRuns', nm->'statusRuns');
      IF r IS NOT NULL THEN
        nm := jsonb_set(nm, '{statusRuns}', r->'runs');
        runs_lost := (r->>'lost')::int; run_players := (r->>'players')::int;
      END IF;
    END IF;
    IF jsonb_typeof(om->'participationDays')='object' AND jsonb_typeof(nm->'participationDays')='object' THEN
      r := public.ps_srm_merge_days(om->'participationDays', nm->'participationDays');
      IF r IS NOT NULL THEN nm := jsonb_set(nm, '{participationDays}', r->'days'); days_lost := (r->>'lost')::int; END IF;
    END IF;
    IF jsonb_typeof(om->'injuryInfo')='object' AND jsonb_typeof(nm->'injuryInfo')='object' THEN
      r := public.ps_srm_merge_injury(om->'injuryInfo', nm->'injuryInfo');
      IF r IS NOT NULL THEN nm := jsonb_set(nm, '{injuryInfo}', r->'info'); inj_lost := (r->>'lost')::int; END IF;
    END IF;

    IF runs_lost + days_lost + inj_lost = 0 THEN RETURN new; END IF;
    new.v := jsonb_set(n, '{meta}', nm)::text;
  EXCEPTION WHEN others THEN
    RETURN new;                      -- 열린 실패: 합치기 오류로 저장을 막지 않는다
  END;

  /* 기록장이 있으면 팀·날마다 한 줄. 기록장 쪽 오류는 저장에 영향을 주지 않는다. */
  BEGIN
    IF to_regclass('public.ps_incidents') IS NOT NULL THEN
      note := '상태 기록 '||runs_lost||'일(선수 '||run_players||') · 출석 칸 '||days_lost||' · 부상 기록 '||inj_lost
              ||' — 저장자 '||coalesce(left(auth.uid()::text, 8), '서버');
      INSERT INTO public.ps_incidents(kind, workspace_id, title, detail)
      SELECT 'near_miss', new.workspace_id, '낡은 사본 저장이 빠뜨린 가용인원 기록을 서버가 합쳐 지킴', note
       WHERE NOT EXISTS (SELECT 1 FROM public.ps_incidents i
                          WHERE i.kind='near_miss' AND i.workspace_id IS NOT DISTINCT FROM new.workspace_id
                            AND i.title='낡은 사본 저장이 빠뜨린 가용인원 기록을 서버가 합쳐 지킴'
                            AND i.at > now() - interval '1 day');
    END IF;
  EXCEPTION WHEN others THEN NULL;
  END;
  RETURN new;
END $function$;

CREATE OR REPLACE FUNCTION public.ps_kv_shape_guard()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare o int; n int; why text;
begin
  if new.k='cs_team_matches_v1' then
    begin
      select count(*) into o from jsonb_array_elements(old.v::jsonb->'matches') m where coalesce(m->>'scoreUs','')<>'' or coalesce(m->>'scoreThem','')<>'';
      select count(*) into n from jsonb_array_elements(new.v::jsonb->'matches') m where coalesce(m->>'scoreUs','')<>'' or coalesce(m->>'scoreThem','')<>'';
    exception when others then return new; end;
    if o>=5 and n<=o/2 then why:='경기 점수 '||o||'개 중 '||(o-n)||'개가 사라지는 저장을 막았어요 — 앱을 새로고침하면 팀 것으로 맞춰져요'; end if;
  elsif new.k in ('cs_squad_v1','scout_tool_v1') then
    begin o:=jsonb_array_length(old.v::jsonb->'players'); n:=jsonb_array_length(new.v::jsonb->'players'); exception when others then return new; end;
    if o>=10 and n>o*1.6 then why:='선수가 '||o||'명에서 '||n||'명으로 갑자기 불어나는 저장을 막았어요(중복 의심) — 앱을 새로고침하면 팀 것으로 맞춰져요';
