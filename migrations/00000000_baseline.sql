CREATE OR REPLACE FUNCTION public.ps_admin_sync_stuck(p_hours integer DEFAULT 48)
 RETURNS TABLE(name text, user_id uuid, fails integer, last_code text, last_stage text, app_version text, last_fail timestamp with time zone, last_write timestamp with time zone, stuck boolean)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if not public.ps_is_admin() then raise exception 'admin only'; end if;
  return query
  with f as (
    select e.user_id, count(*)::int fails, max(e.created_at) last_fail,
           (array_agg(e.error_code order by e.created_at desc))[1] last_code,
           (array_agg(e.meta->>'stage' order by e.created_at desc))[1] last_stage,
           (array_agg(e.app_version order by e.created_at desc))[1] app_version
    from public.ps_events e where e.event_name='sync_failed' and e.created_at >= now() - make_interval(hours => greatest(p_hours,1))
    group by e.user_id),
  w as (select k.updated_by user_id, max(k.updated_at) last_write from public.ps_kv k where k.updated_by is not null group by k.updated_by)
  select m.name, f.user_id, f.fails, f.last_code, f.last_stage, f.app_version, f.last_fail, w.last_write,
         (w.last_write is null or w.last_write < f.last_fail) as stuck
  from f left join w using(user_id)
  left join lateral (select mm.name from public.ps_members mm where mm.user_id=f.user_id and mm.name is not null limit 1) m on true
  order by stuck desc, f.fails desc limit 100;
