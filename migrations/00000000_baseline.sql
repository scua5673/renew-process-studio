CREATE OR REPLACE FUNCTION public.ps_events_rollup(p_keep_days integer DEFAULT 30, p_max_days integer DEFAULT 10)
 RETURNS TABLE(days integer, rows_deleted bigint)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  d date; done integer := 0; del bigint := 0; c bigint;
begin
  for d in
    select distinct created_at::date from public.ps_events
    where created_at < (current_date - p_keep_days)::timestamptz
    order by 1 limit greatest(1, p_max_days)
  loop
    insert into public.ps_events_daily(day,event_name,status,feature,n,users)
    select d, event_name, coalesce(status,'ok'), coalesce(feature,''), count(*), count(distinct user_id)
    from public.ps_events where created_at >= d::timestamptz and created_at < (d + 1)::timestamptz
    group by 1,2,3,4
    on conflict (day,event_name,status,feature) do update
      set n = public.ps_events_daily.n + excluded.n, users = greatest(public.ps_events_daily.users, excluded.users);
    delete from public.ps_events where created_at >= d::timestamptz and created_at < (d + 1)::timestamptz;
    get diagnostics c = row_count; del := del + c; done := done + 1;
  end loop;
  return query select done, del;
end;
$function$;

