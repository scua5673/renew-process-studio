const ring = (cx, cy, r, n) => Array.from({length: n}, (_, i) => {
  const a = i * 2 * Math.PI / n;
  return {type: 'cone', x: Math.round(cx + r * Math.cos(a)), y: Math.round(cy + r * Math.sin(a))};
});
