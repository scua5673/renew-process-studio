const fit = (t, f) => {
  const P = ([x, y]) => f(x, y);
  t.players.forEach(p => { [p.x, p.y] = P([p.x, p.y]); });
  t.equipment.forEach(e => { [e.x, e.y] = P([e.x, e.y]); });
  t.lines.forEach(l => { const k = l.rect ? 'rect' : 'line', v = l[k]; l[k] = [...P(v.slice(0, 2)), ...P(v.slice(2))]; });
  t.ball = P(t.ball);
  t.scenes.forEach(sc => { if (sc.ball) sc.ball = P(sc.ball); for (const k in sc.pos || {}) sc.pos[k] = P(sc.pos[k]); });
  return t;
};
