const PTS = [];
for (let i = 0; i < WAY.length - 1; i++) {
  const p0 = WAY[Math.max(0, i - 1)], p1 = WAY[i], p2 = WAY[i + 1], p3 = WAY[Math.min(WAY.length - 1, i + 2)];
  for (let k = 0; k < 20; k++) {
    const t = k / 20, t2 = t * t, t3 = t2 * t;
    PTS.push([0, 1].map(j => .5 * (2 * p1[j] + (-p0[j] + p2[j]) * t + (2 * p0[j] - 5 * p1[j] + 4 * p2[j] - p3[j]) * t2 + (-p0[j] + 3 * p1[j] - 3 * p2[j] + p3[j]) * t3)));
  }
}
PTS.push(WAY[WAY.length - 1]);
const CUM = [0];
for (let i = 1; i < PTS.length; i++) CUM.push(CUM[i - 1] + Math.hypot(PTS[i][0] - PTS[i - 1][0], PTS[i][1] - PTS[i - 1][1]));
function at(s, side = 0) {
  s = Math.max(0, Math.min(CUM[CUM.length - 1], s));
  let i = 1; while (i < CUM.length - 1 && CUM[i] < s) i++;
  const a = PTS[i - 1], b = PTS[i], f = (s - CUM[i - 1]) / ((CUM[i] - CUM[i - 1]) || 1);
  const dx = b[0] - a[0], dy = b[1] - a[1], L = Math.hypot(dx, dy) || 1;
  return [Math.round(a[0] + dx * f - dy / L * side), Math.round(a[1] + dy * f + dx / L * side)];
}
