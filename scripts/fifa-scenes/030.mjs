const big = t => {
  t.players.forEach(p => { [p.x, p.y] = Z([p.x, p.y]); });
  t.equipment.forEach(e => { [e.x, e.y] = Z([e.x, e.y]); });
  t.lines.forEach(l => { const k = l.rect ? 'rect' : 'line', v = l[k]; l[k] = [...Z(v.slice(0, 2)), ...Z(v.slice(2))]; });
  t.ball = Z(t.ball);
  t.scenes.forEach(sc => { if (sc.ball) sc.ball = Z(sc.ball); for (const k in sc.pos || {}) sc.pos[k] = Z(sc.pos[k]); });
  return t;
};
