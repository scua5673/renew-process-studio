const R = a => Math.round(a);
function area(gx, s, r, cy, post) { // 골라인 gx 의 6m 반원 구역(s = +1 왼쪽 골, -1 오른쪽 골)
  const d = Math.PI / 180, pts = [];
  for (const a of [0, 45, 90]) pts.push([gx + s * r * Math.sin(a * d), cy - post - r * Math.cos(a * d)]);
  for (const a of [90, 45, 0]) pts.push([gx + s * r * Math.sin(a * d), cy + post + r * Math.cos(a * d)]);
  return pts.slice(1).map((p, i) => ({line: [...pts[i], ...p].map(R)}));
}
